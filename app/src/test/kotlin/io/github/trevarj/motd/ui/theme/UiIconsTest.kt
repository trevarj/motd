class UiIconsTest {
    @Test
    fun everyOrdinaryIconPreservesMaterialIdentityAndResolvesCachedLucideGeometry() {
        for (material in ordinaryIcons) {
            assertSame(material.name, material, resolveUiIcon(material, UiIconSet.MATERIAL))
            val lucide = resolveUiIcon(material, UiIconSet.LUCIDE)
            assertNotSame(material.name, material, lucide)
            assertTrue(lucide.name.startsWith("Lucide."))
            assertSame(material.name, lucide, resolveUiIcon(material, UiIconSet.LUCIDE))
            assertEquals(material.autoMirror, lucide.autoMirror)
            assertEquals(24.dp, lucide.defaultWidth)
            assertEquals(24.dp, lucide.defaultHeight)
            assertEquals(24f, lucide.viewportWidth)
            assertEquals(24f, lucide.viewportHeight)
            for (index in 0 until lucide.root.size) {
                val path = lucide.root[index] as VectorPath
                assertEquals(2f, path.strokeLineWidth)
                assertEquals(StrokeCap.Round, path.strokeLineCap)
                assertEquals(StrokeJoin.Round, path.strokeLineJoin)
            }
            assertSame("Restoring Material retains its exact variant", material, resolveUiIcon(material, UiIconSet.MATERIAL))
        }
    }

