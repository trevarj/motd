private val DefaultEmojiCursorBrush: Brush = SolidColor(Color.Black)

@Composable
fun rememberEmojiTextStyle(textStyle: TextStyle): TextStyle {
    val renderer = LocalEmojiRenderer.current ?: return textStyle
    return remember(renderer, textStyle) { renderer.textStyle(textStyle) }
}

@Composable
fun rememberEmojiVisualTransformation(
    existing: VisualTransformation = VisualTransformation.None,
): VisualTransformation {
    val renderer = LocalEmojiRenderer.current ?: return existing
    return remember(renderer, existing) {
        VisualTransformation { text ->
            val transformed = existing.filter(text)
            TransformedText(renderer.annotate(transformed.text), transformed.offsetMapping)
        }
    }
}

@Composable
fun rememberEmojiOutputTransformation(
    existing: OutputTransformation? = null,
): OutputTransformation {
    val renderer = rememberUpdatedState(LocalEmojiRenderer.current)
    val transformation = rememberUpdatedState(existing)
    // A focused state field keys its editing session to this identity, even in System mode.
    return remember {
        OutputTransformation {
            transformation.value?.run { transformOutput() }
            renderer.value?.addStyles(this)
        }
    }
}

