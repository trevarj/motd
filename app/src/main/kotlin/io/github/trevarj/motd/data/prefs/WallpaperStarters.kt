    fun find(id: String): WallpaperStarter? = entries.firstOrNull { it.id == id }

    private fun starter(
        id: String,
        @StringRes label: Int,
        density: Int,
        vararg icons: WallpaperPatternIcon,
        size: Int = 110,
        variation: Int = 180,
    ): WallpaperStarter =
        WallpaperStarter(
            id = id,
            label = label,
            pattern =
                WallpaperPattern(
                    layout = WallpaperPatternLayout.SCATTERED,
                    seed = if (id == "motd") 0x4D4F5444 else id.hashCode(),
                    size = size,
                    density = density,
                    variation = variation,
                    icons = Collections.unmodifiableList(icons.asList()),
                ),
        )

    private fun motif(
        id: String,
        weight: Int = 3,
    ) = WallpaperPatternIcon(assetId = "builtin:$id", weight = weight)

    private fun filler(id: String) = WallpaperPatternIcon(assetId = "builtin:$id", filler = true)
